# apt 源公共模块：env.sh 与 deploy_pc_manager.sh 共用。
#
# 职责：
#   1. 按系统发行版给 /etc/apt/sources.list 写入匹配的软件源
#      （V20=eagle，V25=snipe），写入前备份；
#   2. 隔离 /etc/apt/sources.list.d/*.list 中与本机不匹配的 V25 源
#      （V20 机器混入 V25 源会在装包时连带升级 libc6/systemd/openssh-server，
#      构建期间 sshd/GUI 会失联）；
#   3. 保留原始配置备份（<file>.youqu.bak 与持久副本）；
#      部署流程**不自动还原**——测试机需要保持与系统版本匹配的源，
#      需要回滚时手工调用 restore_apt_sources。
#
# 使用方必须在 source 本模块前设置：
#   APT_SRC_SUDO_CMD   sudo 包装函数名（如 sudo_run / _sudo_pass）
# 可选：
#   PCM_APT_SOURCES_ISOLATED=1  由外层（deploy_pc_manager.sh）负责源配置，
#                               内层仍会写入与系统版本匹配的源。

APT_SOURCES_FILE="${APT_SOURCES_FILE:-/etc/apt/sources.list}"
PCM_APT_PRISTINE_DIR="${PCM_APT_PRISTINE_DIR:-/var/backups/youqu-apt-sources}"
APT_SRC_BACKUP="${APT_SRC_BACKUP:-}"
if [ -z "${APT_SRC_FILES+x}" ]; then
    APT_SRC_FILES=("${APT_SOURCES_FILE}" /etc/apt/sources.list.d/*.list)
fi

_apt_src_sudo() { "${APT_SRC_SUDO_CMD:-sudo}" "$@"; }

_src_active_count() {
    local f="$1"
    grep -cE '^[[:space:]]*deb(-src)?[[:space:]]' "${f}" 2>/dev/null || true
}

_active_deb_source_count() {
    local f total=0 n
    for f in "${APT_SRC_FILES[@]}"; do
        [ -f "${f}" ] || continue
        n="$(_src_active_count "${f}")"
        total=$((total + ${n:-0}))
    done
    printf '%s' "${total}"
}

_pristine_path() {
    printf '%s/%s.orig' "${PCM_APT_PRISTINE_DIR}" "$(basename "$1")"
}

# sources 配置被上一次中断的隔离留在"没有启用源"状态时，用持久备份修复
ensure_apt_sources_active() {
    [ "$(_active_deb_source_count)" -gt 0 ] && return 0
    echo -e "apt源\t没有启用的 deb 源, 尝试用持久备份修复"
    local f bak
    for f in "${APT_SRC_FILES[@]}"; do
        [ -f "${f}" ] || continue
        bak="$(_pristine_path "${f}")"
        [ -f "${bak}" ] || continue
        _apt_src_sudo cp -a "${bak}" "${f}"
        echo -e "apt源\t已从持久备份恢复: ${f}"
    done
    if [ "$(_active_deb_source_count)" -gt 0 ]; then
        echo -e "apt源\t已由持久备份修复"
        return 0
    fi
    echo -e "apt源\t\x1b[31m没有启用的 deb 源, apt 不可用, 请人工修复\x1b[0m" >&2
    return 1
}

# ---------------------------------------------------------------- 版本源模板
_v20_sources() {
    cat <<'EOF'
deb http://pools.uniontech.com/desktop-professional eagle main contrib non-free
deb http://pools.uniontech.com/ppa/dde-eagle eagle/1076 main contrib non-free
deb http://pools.uniontech.com/ppa/dde-eagle-driver eagle/1074 main contrib non-free
deb http://pools.uniontech.com/ppa/dde-eagle-udcp/  eagle main contrib non-free ## udcp 域管独立仓库
###  deb http://pools.uniontech.com/desktop-professional-rsync-security/  eagle/1070 main contrib non-free  ## 安全仓库
EOF
}

_v25_sources() {
    cat <<'EOF'
## Generated by Iso-Builder
deb [trusted=yes] http://pools.uniontech.com/desktop-professional-V25 snipe main community commercial
deb [trusted=yes] http://pools.uniontech.com/ppa/dde-snipe snipe/2500u2 main community commercial
deb [trusted=yes] http://pools.uniontech.com/ppa/udcp-snipe snipe/2500u2 main community commercial
deb http://pro-store-packages.uniontech.com/appstore-V25/ snipe appstore
deb [trusted=yes] http://pools.uniontech.com/driver-V25/ snipe non-free
EOF
}

detect_release_major() {
    local major=""
    major=$(sed -n 's/^VERSION_ID="\{0,1\}\([0-9][0-9]*\).*/\1/p' "${APT_OS_RELEASE:-/etc/os-release}" 2>/dev/null)
    case "${major}" in
        20 | 25)
            printf '%s' "${major}"
            return 0
            ;;
    esac
    # VERSION_ID 缺失时按当前源代号兜底：snipe 为 V25，其余按 V20 处理
    if grep -qE 'snipe' "${APT_SOURCES_FILE}" 2>/dev/null; then
        printf '25'
    else
        printf '20'
    fi
}

# 写入与系统版本匹配的源；原始文件备份为 <file>.youqu.bak（另有持久副本）。
# 写入后**不自动还原**：部署/环境初始化后测试机需要保持正确源。
APT_SOURCES_APPLIED=0
apply_release_apt_sources() {
    local major tmp
    major=$(detect_release_major)
    if [ ! -f "${APT_SOURCES_FILE}" ]; then
        _apt_src_sudo touch "${APT_SOURCES_FILE}"
    fi
    _apt_src_sudo mkdir -p "${PCM_APT_PRISTINE_DIR}" >/dev/null 2>&1
    if [ ! -f "$(_pristine_path "${APT_SOURCES_FILE}")" ]; then
        _apt_src_sudo cp -a "${APT_SOURCES_FILE}" "$(_pristine_path "${APT_SOURCES_FILE}")"
    fi
    if [ ! -f "${APT_SOURCES_FILE}.youqu.bak" ]; then
        _apt_src_sudo cp -a "${APT_SOURCES_FILE}" "${APT_SOURCES_FILE}.youqu.bak"
    fi
    tmp=$(mktemp /tmp/youqu_sources.XXXXXX)
    case "${major}" in
        25) _v25_sources >"${tmp}" ;;
        *) _v20_sources >"${tmp}" ;;
    esac
    _apt_src_sudo cp -a "${tmp}" "${APT_SOURCES_FILE}"
    _apt_src_sudo chmod 644 "${APT_SOURCES_FILE}"
    rm -f "${tmp}"
    case " ${APT_SRC_BACKUP} " in
        *" ${APT_SOURCES_FILE} "*) ;;
        *) APT_SRC_BACKUP="${APT_SRC_BACKUP} ${APT_SOURCES_FILE}" ;;
    esac
    APT_SOURCES_APPLIED=1
    echo -e "apt源\t已按系统版本 V${major} 写入源配置: ${APT_SOURCES_FILE}"
    # 源变更后必须刷新索引，否则 apt 仍用旧源的 Packages 列表（域名/组件
    # 不同会直接 404 或装到错误版本）。失败不中止：离线环境仍可继续。
    if [ "${PCM_APT_SKIP_UPDATE:-0}" != "1" ]; then
        echo -e "apt源\t更新源索引(apt-get update)"
        if _apt_src_sudo env DEBIAN_FRONTEND=noninteractive apt-get update >/tmp/youqu_apt_update.log 2>&1; then
            echo -e "apt源\t源索引更新完成"
        else
            echo -e "apt源\t\x1b[33mapt-get update 失败, 继续(详见 /tmp/youqu_apt_update.log)\x1b[0m"
            tail -n 5 /tmp/youqu_apt_update.log 2>/dev/null || true
        fi
    fi
    return 0
}

# 注释 sources.list.d/*.list 中的 V25 源（仅 V20 系统需要）。
# 已由 apply_release_apt_sources 写入正确源时，即使某文件的启用条目
# 全是 V25 也可以安全注释，不会出现"没有任何启用源"。
isolate_v25_sources() {
    local os_major="" f active v25 others
    os_major=$(sed -n 's/^VERSION_ID="\{0,1\}\([0-9][0-9]*\).*/\1/p' "${APT_OS_RELEASE:-/etc/os-release}" 2>/dev/null)
    [ "${os_major}" = "20" ] || return 0
    _apt_src_sudo mkdir -p "${PCM_APT_PRISTINE_DIR}" >/dev/null 2>&1
    for f in "${APT_SRC_FILES[@]}"; do
        [ -f "${f}" ] || continue
        grep -qE 'pools\.uniontech\.com/(desktop-professional-V25|ppa/dde-snipe)' "${f}" 2>/dev/null || continue
        if [ "${APT_SOURCES_APPLIED}" != "1" ]; then
            # 未写入版本源时，若该文件启用条目全是 V25，隔离=清空全部源，
            # 不做隔离，留待人工修正。
            active=$(_src_active_count "${f}")
            v25=$(grep -cE '^[[:space:]]*deb(-src)?[[:space:]].*pools\.uniontech\.com/(desktop-professional-V25|ppa/dde-snipe)' "${f}" 2>/dev/null || true)
            others=$((active - v25))
            if [ "${active}" -gt 0 ] && [ "${others}" -le 0 ]; then
                echo -e "apt源\t${f} 的启用条目全部为 V25 源（与本机系统不匹配），跳过隔离，请人工配置正确源"
                continue
            fi
        fi
        # 持久备份：首次隔离前保存，退出后保留，供异常中断时修复
        if [ ! -f "$(_pristine_path "${f}")" ]; then
            _apt_src_sudo cp -a "${f}" "$(_pristine_path "${f}")"
        fi
        # 运行期备份存在（上一次中断留下）时沿用，避免用已注释的文件覆盖原始内容
        if [ ! -f "${f}.youqu.bak" ]; then
            _apt_src_sudo cp -a "${f}" "${f}.youqu.bak"
        fi
        _apt_src_sudo sed -i -E 's#^(deb(-src)?[[:space:]].*pools\.uniontech\.com/(desktop-professional-V25|ppa/dde-snipe).*)$#\#\1#' "${f}"
        case " ${APT_SRC_BACKUP} " in
            *" ${f} "*) ;;
            *) APT_SRC_BACKUP="${APT_SRC_BACKUP} ${f}" ;;
        esac
        echo -e "apt源\t已临时禁用 V25 源: ${f}"
    done
    return 0
}

# 人工回滚入口：把 *.youqu.bak 还原为正式配置。
# 部署脚本与 env.sh **不再自动调用**——写入的版本源需要保持生效。
# 如需恢复部署前的源：
#   bash -c 'APT_SRC_SUDO_CMD=sudo; source src/utils/apt_sources.sh; restore_apt_sources'
restore_apt_sources() {
    local f restored=0
    for f in "${APT_SRC_FILES[@]}" ${APT_SRC_BACKUP}; do
        [ -f "${f}.youqu.bak" ] || continue
        _apt_src_sudo mv -f "${f}.youqu.bak" "${f}"
        echo -e "apt源\t已恢复: ${f}"
        restored=1
    done
    if [ "${restored}" = "0" ]; then
        echo -e "apt源\t没有可恢复的备份(.youqu.bak)"
    fi
    ensure_apt_sources_active || true
    APT_SRC_BACKUP=""
    APT_SOURCES_APPLIED=0
    return 0
}
